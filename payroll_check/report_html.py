STATUS_TEXT = {"ok": "OK", "review": "Review", "missing": "Missing"}


def _diff(value) -> str:
    cls = "pos" if value > 0 else "neg" if value < 0 else ""
    return f'<td class="num {cls}">{fmt_money(value, signed=True) if value else "—"}</td>'


def render_html(result: Reconciliation, period: str = "") -> str:
    a, b = escape(result.settings.label_a), escape(result.settings.label_b)
    matching = sum(1 for e in result.employees if e.status == "ok")
    tiles = [
        ("Employees fully matching", f"{matching} of {len(result.employees)}"),
        ("Net difference", fmt_money(result.total_net_b - result.total_net_a, signed=True)),
        ("Errors", str(result.count(ERROR))),
        ("Warnings", str(result.count(WARNING))),
    ]
    tiles_html = "".join(f'<div class="tile"><div class="label">{l}</div><div class="value">{v}</div></div>'
                         for l, v in tiles)

    rows = "".join(
        "<tr>"
        f"<td>{escape(e.name)}</td>"
        f'<td><span class="badge {e.status}">{STATUS_TEXT[e.status]}</span></td>'
        f'<td class="num">{fmt_money(e.totals_a.net) if e.in_a else "—"}</td>'
        f'<td class="num">{fmt_money(e.totals_b.net) if e.in_b else "—"}</td>'
        f"{_diff(e.net_difference)}<td class=\"num\">{e.issues or ''}</td>"
        "</tr>"
        for e in result.employees
    )
    issue_rows = "".join(
        "<tr>"
        f'<td><span class="badge {i.severity}">{i.severity}</span></td>'
        f"<td>{escape(i.employee_name)}</td><td>{i.code}</td>"
        f'<td class="details">{escape(i.message)}</td>'
        "</tr>"
        for i in result.issues
    ) or '<tr><td colspan="4">Both sides match.</td></tr>'

    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Payroll reconciliation</title>
<style>{CSS}</style>
</head>
<body>
<div class="wrap">
  <h1>Payroll reconciliation{' · ' + escape(period) if period else ''}</h1>
  <p class="sub">{a} compared with {b}, item by item and employee by employee.</p>
  <div class="tiles">{tiles_html}</div>

  <h2>Employees</h2>
  <div class="card"><table>
    <thead><tr><th>Employee</th><th>Status</th><th>Net · {a}</th><th>Net · {b}</th><th>Difference</th><th>Issues</th></tr></thead>
    <tbody>{rows}</tbody>
  </table></div>

  <h2>Issues to review ({len(result.issues)})</h2>
  <div class="card"><table>
    <thead><tr><th>Severity</th><th>Employee</th><th>Issue</th><th>Details</th></tr></thead>
    <tbody>{issue_rows}</tbody>
  </table></div>

  <footer>Generated by payroll-reconciliation. Positive differences mean {b} pays more than {a}.</footer>
</div>
</body>
</html>
"""


def write_html(result: Reconciliation, path: str | Path, period: str = "") -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_html(result, period), encoding="utf-8")
    return path
